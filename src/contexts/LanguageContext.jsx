export function LanguageProvider({ children }) {
    const [language, setLanguage] = useState(() => {
        const saved = localStorage.getItem('jobportal_lang');
        return saved === 'en' || saved === 'vi' ? saved : 'vi';
    });

    useEffect(() => {
        localStorage.setItem('jobportal_lang', language);
        document.documentElement.setAttribute('lang', language);
    }, [language]);

    const toggleLanguage = () => {
        setLanguage((prev) => (prev === 'vi' ? 'en' : 'vi'));
    };

    const t = (key, fallback = '') => {
        if (!translations[language]) return fallback || key;
        return translations[language][key] || fallback || key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t, isEn: language === 'en' }}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
}

// Reusable LanguageToggle button
export function LanguageToggle({ className = '', showLabel = true }) {
    const { language, toggleLanguage, isEn } = useLanguage();

    return (
        <button
            type="button"
            onClick={toggleLanguage}
            className={`flex items-center space-x-1.5 px-2.5 py-1.5 rounded-lg border transition cursor-pointer select-none ${
                isEn
                    ? 'bg-blue-50/80 hover:bg-blue-100 text-blue-900 border-blue-200 dark:bg-slate-800 dark:hover:bg-slate-700 dark:text-blue-300 dark:border-slate-700 shadow-xs'
                    : 'bg-rose-50/80 hover:bg-rose-100 text-rose-900 border-rose-200 dark:bg-slate-800 dark:hover:bg-slate-700 dark:text-rose-300 dark:border-slate-700 shadow-xs'
            } ${className}`}
            title={isEn ? 'Switch to Vietnamese (Tiếng Việt)' : 'Chuyển sang Tiếng Anh (English)'}
            aria-label="Chuyển đổi ngôn ngữ Tiếng Việt / English"
        >
            <span className="text-sm leading-none shrink-0" role="img" aria-hidden="true">
                {isEn ? '🇬🇧' : '🇻🇳'}
            </span>
            {showLabel && (
                <span className="text-xs font-bold uppercase tracking-wider">
                    {isEn ? 'EN' : 'VI'}
                </span>
            )}
        </button>
    );
}
